// Copy-ready palettes for the /best-colors-for industry pages. Each one names the job
// of every color (primary, secondary, accent, background, text) so the page can draw a
// small website preview with it and compute its real WCAG contrast. Every palette here
// gives AAA body text and at least AA for buttons, links, badges and cards - check new
// ones the same way before adding them.

function palette(
  name: string,
  useCase: string,
  colors: string[],
  [primary, secondary, accent, background, text]: [string, string, string, string, string],
  note: string,
): ReadyPalette {
  return { name, useCase, colors, roles: { primary, secondary, accent, background, text }, note };
}

